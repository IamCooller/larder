IQ2S_GRID = _grid(_IQ2S_HEX, _IQ2S_VALS, 8, 2)
IQ2XXS_GRID = _grid(_IQ2XXS_HEX, _IQ2S_VALS, 8, 2)
IQ2XS_GRID = _grid(_IQ2XS_HEX, _IQ2S_VALS, 8, 2)
IQ3S_GRID = _grid(_IQ3S_HEX, (1, 3, 5, 7, 9, 11, 13, 15), 4, 3)
