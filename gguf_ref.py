def _grid(hexs, vals, per, bits, dtype=np.uint8):
    """A packed grid as an array [entries, per] of dtype (uint8, or int8 for iq1s)."""
    w = per * bits // 4
    codes = np.array([int(hexs[i:i + w], 16) for i in range(0, len(hexs), w)], np.uint32)
    idx = (codes[:, None] >> (np.arange(per, dtype=np.uint32) * bits)) & ((1 << bits) - 1)
    return np.array(vals, dtype)[idx]


