def _q2_k(b):
    """Weight 128h + 32j + l: 2 bits at 2j of qs[32h + l], scale and min nibbles of byte 8h + 2j + l // 16."""
    n = b.shape[0]
    sc = b[:, 0:16].reshape(n, 2, 4, 2, 1)
    q = (b[:, 16:80].reshape(n, 2, 1, 32) >> (2 * np.arange(4, dtype=np.uint8)).reshape(1, 1, 4, 1)) & 3
    dl = _f16(b, 80).reshape(n, 1, 1, 1, 1) * (sc & 0xF).astype(np.float32)
    ml = _f16(b, 82).reshape(n, 1, 1, 1, 1) * (sc >> 4).astype(np.float32)
    return (dl * q.reshape(n, 2, 4, 2, 16).astype(np.float32) - ml).reshape(n, 256)


def _q3_k(b):
    """Weight 128h + 32j + l: 2 bits at 2j of qs[32h + l] less 4 where bit 4h + j of hmask[l] is clear."""
    n = b.shape[0]
    s = b[:, 96:108].astype(np.int32)
    i = np.arange(16)
    low = np.where(i < 8, s[:, i % 8] & 0xF, s[:, i % 8] >> 4)
    sc = (low | ((s[:, 8 + i % 4] >> (2 * (i // 4))) & 3) << 4) - 32                   # (n, 16)
    dl = _f16(b, 108)[:, None] * sc.astype(np.float32)
    j = np.arange(4).reshape(1, 1, 4, 1)
    q2 = (b[:, 32:96].reshape(n, 2, 1, 32).astype(np.int32) >> (2 * j)) & 3
    hb = (b[:, 0:32].reshape(n, 1, 1, 32).astype(np.int32) >> (4 * np.arange(2).reshape(1, 2, 1, 1) + j)) & 1
    q = (q2 - np.where(hb == 1, 0, 4)).astype(np.float32).reshape(n, 2, 4, 2, 16)
    return (dl.reshape(n, 2, 4, 2, 1) * q).reshape(n, 256)


def _q6_k(b):
    """Weight 128h + 32g + l: nibble g // 2 of ql[64h + 32 (g % 2) + l], 2 bits at 2g of qh[32h + l], minus 32."""
    n = b.shape[0]
    g = np.arange(4).reshape(1, 1, 4, 1)
    ql = b[:, 0:128].reshape(n, 2, 2, 32).astype(np.int32)[:, :, [0, 1, 0, 1], :]
    ql = (ql >> (4 * (g // 2))) & 0xF
    qh = (b[:, 128:192].reshape(n, 2, 1, 32).astype(np.int32) >> (2 * g)) & 3
    q = ((ql | qh << 4) - 32).astype(np.float32).reshape(n, 2, 4, 2, 16)
    sc = b[:, 192:208].view(np.int8).astype(np.float32).reshape(n, 2, 4, 2, 1)
    return ((_f16(b, 208).reshape(n, 1, 1, 1, 1) * sc) * q).reshape(n, 256)


