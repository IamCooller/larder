def ref_dequant(raw, t):
    """float32 weights of `raw` (bytes or uint8 array) in ggml type t (a name of TYPES), ggml's
    dequantize_row_* without fused multiply-adds."""
    _, be, bb = TYPES[t]
    b = np.frombuffer(raw, np.uint8) if isinstance(raw, (bytes, bytearray, memoryview)) else np.asarray(raw, np.uint8)
    assert b.size % bb == 0, (t, b.size)
    with np.errstate(over="ignore", invalid="ignore"):
        return _REF[t](b.reshape(-1, bb)).reshape(-1).astype(np.float32, copy=False)


# Byte offsets of each type's f16 fields in a block (d, and dmin or m); the other types' scales are handled apart.
HALVES = {"Q4_0": (0,), "Q4_1": (0, 2), "Q4_K": (0, 2), "Q5_K": (0, 2), "Q5_1": (0, 2), "Q5_0": (0,), "Q8_0": (0,),
          "Q2_0": (0,),
          "IQ4_NL": (0,), "IQ4_XS": (0,), "IQ3_XXS": (0,), "IQ2_S": (0,), "Q2_K": (80, 82), "Q3_K": (108,),
          "Q6_K": (208,), "IQ2_XXS": (0,), "IQ2_XS": (0,), "IQ3_S": (0,), "IQ1_S": (0,), "TQ1_0": (52,),
          "TQ2_0": (64,), "Q1_0": (0,)}


def valid(b, t):
    """Whether blocks b (n, block bytes) of type t pass ggml_validate_row_data, llama.cpp's load-time check: f16
    scales and float values finite, MXFP4 exponents below 0xFF, no F8_E4M3 NaN."""
    b = np.asarray(b, np.uint8).reshape(-1, TYPES[t][2])
    if t in HALVES:
        h = np.concatenate([np.ascontiguousarray(b[:, a:a + 2]).view("<u2") for a in HALVES[t]], axis=1)
    elif t == "IQ1_M":
        h = _iq1_m_d(b)[0]
    elif t in ("F16", "BF16", "F32"):
        dt, exp = {"F16": ("<u2", 0x7C00), "BF16": ("<u2", 0x7F80), "F32": ("<u4", 0x7F800000)}[t]
        return not ((np.ascontiguousarray(b).view(dt) & exp) == exp).any()
    elif t == "MXFP4":
        return not (b[:, 0] == 0xFF).any()
    elif t == "F8_E4M3":
        return not ((b[:, 0] & 0x7F) == 0x7F).any()
    else:
        return True                     # NVFP4: ggml checks nothing yet
    return not ((h & 0x7C00) == 0x7C00).any()


def random_experts(rng, n, rows, length, t, scale=0.01):
    """n random experts [n, rows, row bytes] of type t with finite scales (~scale), as numpy uint8."""
    _, be, bb = TYPES[t]
    b = rng.integers(0, 256, (n * rows * length // be, bb), dtype=np.uint8)
    half = lambda k: (rng.standard_normal((len(b), k)) * scale).astype(np.float16).view(np.uint8)  # noqa: E731
    for at in HALVES.get(t, ()):
        b[:, at:at + 2] = half(1)
    if t == "IQ1_M":                    # d's four nibbles at the top of the four scale words
        d = half(1).view("<u2")[:, 0].astype(np.uint16)
        sc = np.ascontiguousarray(b[:, 48:56]).view("<u2") & 0x0FFF
        sc |= ((d[:, None] >> (4 * np.arange(4, dtype=np.uint16))) & 0xF) << 12
        b[:, 48:56] = sc.view(np.uint8)
    elif t == "MXFP4":                  # 2^(e - 128) of ~scale / 4
        b[:, 0] = rng.integers(117, 122, len(b))
    elif t == "NVFP4":                  # exponent 1..3: 2^-7 .. 2^-4
        b[:, 0:4] = rng.integers(8, 32, (len(b), 4))
    elif t == "F8_E4M3":                # exponent 0..4, any sign and mantissa
        b[:, 0] = rng.integers(0, 40, len(b)) | (rng.integers(0, 2, len(b)) << 7)
    elif t in ("F16", "BF16", "F32"):
        v = rng.standard_normal(len(b)).astype(np.float32) * np.float32(scale)
        b[:] = (v.astype(np.float16).view(np.uint8) if t == "F16" else
                (v.view(np.uint32) >> 16).astype(np.uint16).view(np.uint8) if t == "BF16" else v.view(np.uint8)
                ).reshape(len(b), bb)
    return b.reshape(n, rows, length // be * bb)
