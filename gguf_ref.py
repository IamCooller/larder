    dl = d[:, None, None] * (2 * (s & 7) + 1).astype(np.float32)
    qh = b[:, 32:48].reshape(n, 8, 2, 1).astype(np.int32) >> np.array([0, 4])                 # (n, 8, 2, 2): nibbles
    idx = b[:, 0:32].reshape(n, 8, 2, 2).astype(np.int32) | ((qh & 7) << 8)
    delta = np.where(qh & 8, -_DELTA, _DELTA)
    g = IQ1S_GRID[idx].astype(np.float32)                                                    # (n, 8, 2, 2, 8)
    return (dl[:, :, :, None, None] * (g + delta[..., None])).reshape(n, 256)


