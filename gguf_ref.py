    q = np.concatenate([qs & 0xF, qs >> 4], axis=1).astype(np.int32)
    if not with_min:
        return (q - 8).astype(np.float32) * _f16(b, 0)[:, None]
    return q.astype(np.float32) * _f16(b, 0)[:, None] + _f16(b, 2)[:, None]


